#!/usr/bin/env python3
"""Generate other agent CLIs' config from .claude/, so Codex and Antigravity
get the same skills, MCP servers and as many guardrails as their formats allow.

.claude/ and .mcp.json stay the single source. Everything this writes is derived,
carries a "generated" note where the format allows one, and is checked in CI:

    python scripts/gen-vendor-configs.py            # write
    python scripts/gen-vendor-configs.py --check    # exit 1 if anything is stale (CI)
    python scripts/gen-vendor-configs.py --self-check

| Source                         | Codex                      | Antigravity            |
|--------------------------------|----------------------------|------------------------|
| AGENTS.md                      | read natively              | read natively          |
| .claude/skills/                | .agents/skills/ (shared)   | .agents/skills/        |
| .claude/rules/                 | linked from AGENTS.md      | .agents/rules/         |
| .claude/commands/              | (none: describe the task)  | (none)                 |
| .claude/agents/                | .codex/agents/*.toml       | (none)                 |
| .mcp.json                      | .codex/config.toml         | .agents/mcp_config.json|
| permissions Bash allow/ask/deny| .codex/rules/*.rules       | (user settings only)   |
| permissions Read deny          | (none)                     | (user settings only)   |
| hooks PreToolUse "Bash"        | .codex/hooks.json          | (payload differs)      |

Whatever doesn't carry over is listed per CLI in docs/reference/OTHER-CLIS.md, so an agent
under another CLI knows which guardrail it is running without. Codex loads a project's
.codex/ only once the user has trusted the folder.

Gemini CLI is no longer a target (dropped 2026-10-22). `.gemini/` and `.geminiignore` stay in
OWNED so the next run deletes what an older version generated; --check reports them until then.

ponytail: regex frontmatter parse and hand-written TOML, same as the other scripts here.
The inputs are shallow and hand-written; reach for PyYAML/tomli-w when one nests.
"""
import argparse
import json
import re
import sys
import tempfile
from pathlib import Path

FRONTMATTER_RE = re.compile(r"\A---\r?\n(.*?)\r?\n---\r?\n?", re.DOTALL)
BASH_RE = re.compile(r"\ABash\((.+)\)\Z")
NOTE = "Generated by scripts/gen-vendor-configs.py from .claude/ and .mcp.json. Do not edit by hand."
DOC = "docs/reference/OTHER-CLIS.md"
# Gemini CLI output from older versions: still owned, so a regen removes it, never generated.
RETIRED = (".gemini", ".geminiignore")
# Paths this script owns. Anything else under .agents/ is left alone.
OWNED = [".agents/skills", ".agents/rules", ".agents/mcp_config.json", ".codex", *RETIRED, DOC]


# ---------------------------------------------------------------- reading


def unquote(value: str) -> str:
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        value = value[1:-1].replace('\\"', '"').replace("\\n", "\n")
    return value.strip()


def split_frontmatter(text: str) -> tuple[dict[str, str], str]:
    m = FRONTMATTER_RE.match(text)
    if not m:
        return {}, text
    out: dict[str, str] = {}
    key = None
    for line in m.group(1).splitlines():
        if not line.strip():
            continue
        if line[:1] in " \t" and key:
            out[key] += " " + line.strip()
            continue
        if ":" in line:
            key, _, value = line.partition(":")
            key = key.strip()
            out[key] = unquote(value.strip())
    return out, text[m.end():]


def bash_prefix(rule: str) -> list[str] | None:
    """`Bash(git push:*)` -> ["git", "push"]; None for anything that isn't a plain prefix."""
    m = BASH_RE.match(rule)
    if not m:
        return None
    spec = m.group(1)
    spec = spec.removesuffix(":*")
    if any(c in spec for c in "*?[]"):
        return None
    return spec.split() or None


def load_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else {}


# ---------------------------------------------------------------- writing helpers


def toml_str(s: str) -> str:
    """A TOML basic string. JSON's escapes are a subset of TOML's for these inputs."""
    return json.dumps(s, ensure_ascii=False)


def toml_multiline(s: str) -> str:
    return f"'''\n{s}'''" if "'''" not in s and not s.endswith("'") else toml_str(s)


def dump_json(obj) -> str:
    return json.dumps(obj, indent=2, ensure_ascii=False) + "\n"


def relative_hook(command: str) -> str:
    """Claude hook commands anchor on $CLAUDE_PROJECT_DIR; other CLIs run hooks from the project root."""
    return re.sub(r"\$\{?CLAUDE_PROJECT_DIR\}?[/\\]", "", command)


# ---------------------------------------------------------------- the mapping


def build(root: Path) -> tuple[dict[str, bytes], dict[str, list[str]]]:
    """Every generated file as {relative path: bytes}, plus the gaps per CLI."""
    files: dict[str, bytes] = {}
    gaps: dict[str, list[str]] = {"Codex": [], "Antigravity": []}

    def put(rel: str, text: str) -> None:
        files[rel] = text.encode("utf-8")

    claude = root / ".claude"
    settings = load_json(claude / "settings.json")
    perms = settings.get("permissions", {})
    mcp = load_json(root / ".mcp.json").get("mcpServers", {})

    # Skills: one shared copy that both CLIs read.
    for skill_md in sorted((claude / "skills").glob("*/SKILL.md")):
        for f in sorted(skill_md.parent.rglob("*")):
            if f.is_file() and "__pycache__" not in f.parts:
                files[f".agents/skills/{f.relative_to(claude / 'skills').as_posix()}"] = f.read_bytes()

    # Rules: Antigravity drops a rule file without a trigger.
    for rule in sorted((claude / "rules").glob("*.md")):
        body = rule.read_text(encoding="utf-8")
        title = next((ln.lstrip("# ").strip() for ln in body.splitlines() if ln.startswith("#")), rule.stem)
        put(f".agents/rules/{rule.name}", f"---\ntrigger: always_on\ndescription: {toml_str(title)}\n---\n<!-- {NOTE} -->\n\n{body}")

    # Commands: Codex and Antigravity turned commands into skills; we don't duplicate them.
    commands = sorted((claude / "commands").glob("*.md"))
    if commands:
        names = ", ".join(f"`/{c.stem}`" for c in commands)
        gaps["Codex"].append(f"Commands ({names}) aren't generated: describe the task and the matching skill loads.")
        gaps["Antigravity"].append(f"Commands ({names}) aren't generated: describe the task and the matching skill loads.")

    # Agents: Codex has repo-level agent definitions with instructions but no per-agent tool list.
    agents = sorted((claude / "agents").glob("*.md"))
    for agent in agents:
        fm, body = split_frontmatter(agent.read_text(encoding="utf-8"))
        desc = re.split(r"\s*(?:Specifically:|<example>)", fm.get("description", ""), maxsplit=1)[0].strip()
        tools = fm.get("tools", "")
        instr = body.strip("\n") + "\n"
        if tools:
            instr = f"In Claude Code this agent may only use: {tools}. Keep to that here: if it can't edit, don't edit.\n\n" + instr
        put(f".codex/agents/{agent.stem}.toml",
            f"# {NOTE}\nname = {toml_str(fm.get('name', agent.stem))}\ndescription = {toml_str(desc)}\n"
            f"developer_instructions = {toml_multiline(instr)}\n")
    if agents:
        names = ", ".join(f"`{a.stem}`" for a in agents)
        gaps["Antigravity"].append(f"Reviewer agents ({names}) aren't generated (their tool names differ): ask for the review and point the session at `.claude/agents/<name>.md`.")
        gaps["Codex"].append(f"Reviewer agents ({names}) carry their tool limits as an instruction only; Codex has no per-agent tool list.")

    # MCP servers.
    codex_mcp, agy_mcp = [], {}
    for name, s in mcp.items():
        if s.get("type") in ("http", "sse") or "url" in s:
            codex_mcp.append(f"[mcp_servers.{name}]\nurl = {toml_str(s['url'])}\n")
            agy_mcp[name] = {"serverUrl": s["url"]}
            continue
        entry = {"command": s["command"], "args": s.get("args", [])}
        if s.get("env"):
            entry["env"] = s["env"]
        block = f"[mcp_servers.{name}]\ncommand = {toml_str(entry['command'])}\nargs = [{', '.join(toml_str(a) for a in entry['args'])}]\n"
        if s.get("env"):
            block += "env = { " + ", ".join(f"{k} = {toml_str(v)}" for k, v in s["env"].items()) + " }\n"
        codex_mcp.append(block)
        agy_mcp[name] = dict(entry)
    if codex_mcp:
        put(".codex/config.toml", f"# {NOTE}\n\n" + "\n".join(codex_mcp))
    if agy_mcp:
        put(".agents/mcp_config.json", dump_json({"mcpServers": agy_mcp}))

    # Command permissions.
    decisions = {"allow": "allow", "ask": "prompt", "deny": "forbidden"}
    rules, unmapped = [], []
    for kind in ("deny", "ask", "allow"):
        for r in perms.get(kind, []):
            prefix = bash_prefix(r)
            if prefix is None:
                unmapped.append((kind, r))
                continue
            pattern = ", ".join(toml_str(t) for t in prefix)
            rules.append(f'prefix_rule(pattern=[{pattern}], decision="{decisions[kind]}", justification="{kind} in .claude/settings.json")')
    if rules:
        put(".codex/rules/workspace.rules", f"# {NOTE}\n# Strictest match wins; covers commands only, not file reads.\n\n" + "\n".join(rules) + "\n")
    for kind, r in unmapped:
        if kind == "allow":
            continue  # a grant that doesn't carry over only means more prompts, not a lost guardrail
        gaps["Codex"].append(f"`{r}` ({kind}) has no equivalent: Codex rules cover commands only.")

    # Hooks: only PreToolUse on Bash maps cleanly (same payload: tool_input.command).
    codex_hooks = []
    for event, entries in settings.get("hooks", {}).items():
        for e in entries:
            for h in e.get("hooks", []):
                cmd = relative_hook(h.get("command", ""))
                if event == "PreToolUse" and e.get("matcher") == "Bash":
                    codex_hooks.append({"matcher": "Bash", "hooks": [{"type": "command", "command": cmd}]})
                    gaps["Antigravity"].append(f"The `{event}` hook `{cmd}` doesn't run: Antigravity's hook payload has a different shape. Its guard does not apply.")
                else:
                    for items in gaps.values():
                        items.append(f"The `{event}` hook `{cmd}` (matcher `{e.get('matcher', '*')}`) is Claude Code only.")
    if codex_hooks:
        put(".codex/hooks.json", dump_json({"hooks": {"PreToolUse": codex_hooks}}))

    if perms:
        gaps["Antigravity"].append("No repo-level permissions file exists: none of `.claude/settings.json`'s allow, ask or deny rules apply. "
                                   "Set them in your user `settings.json` (`~/.gemini/antigravity-cli/`) or the app before working here.")
    gaps["Codex"].insert(0, "Codex loads `.codex/` only after you trust this folder; "
                            "until then none of its settings, rules, hooks or MCP servers apply.")

    put(DOC, render_doc(root, files, gaps))
    return files, gaps


def render_doc(root: Path, files: dict[str, bytes], gaps: dict[str, list[str]]) -> str:
    gen = sorted(p for p in files if not p.startswith(".agents/skills/"))
    skills = sorted({p.split("/")[2] for p in files if p.startswith(".agents/skills/")})
    out = [f"<!-- {NOTE} -->", "", "# 🔀 Other agent CLIs", "",
           ("This workspace is built for Claude Code (`.claude/`), and `scripts/gen-vendor-configs.py` "
            "derives what it can for Codex and Antigravity. `AGENTS.md` is the doctrine for all of "
            "them. Edit `.claude/` or `.mcp.json`, then rerun the script; never edit the generated files."), "",
           "## What carries over", "",
           f"- **Skills** ({len(skills)}): `.agents/skills/`, read by both." if skills else "- **Skills:** none wired.",
           "- **Generated files:** " + ", ".join(f"`{p}`" for p in gen if p != DOC), "",
           "## What doesn't, per CLI", "",
           "Read this before relying on a guardrail outside Claude Code.", ""]
    for cli, items in gaps.items():
        out.append(f"### {cli}")
        out.append("")
        out.extend(f"- {i}" for i in items) if items else out.append("- Nothing beyond the notes above.")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


# ---------------------------------------------------------------- write / check


def existing(root: Path) -> set[str]:
    found = set()
    for owned in OWNED:
        p = root / owned
        if p.is_file():
            found.add(owned)
        elif p.is_dir():
            found |= {f.relative_to(root).as_posix() for f in p.rglob("*") if f.is_file()}
    return found


def norm(b: bytes) -> bytes:
    return b.replace(b"\r\n", b"\n")


def run(root: Path, check: bool) -> int:
    files, _ = build(root)
    have = existing(root)
    stale = sorted(p for p, b in files.items() if p not in have or norm((root / p).read_bytes()) != norm(b))
    extra = sorted(have - set(files))
    if check:
        for p in stale:
            print(f"stale: {p}")
        for p in extra:
            if p.split("/")[0] in RETIRED:
                print(f"retired Gemini CLI output (a regen deletes it): {p}")
            else:
                print(f"not generated (remove it, or add its source to .claude/): {p}")
        if stale or extra:
            print("run: python scripts/gen-vendor-configs.py")
            return 1
        print(f"vendor configs are current ({len(files)} files)")
        return 0
    for p in extra:
        (root / p).unlink()
    for p in stale:
        dest = root / p
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(files[p])
    for owned in OWNED:  # drop directories the removals emptied
        d = root / owned
        if d.is_dir():
            for sub in sorted((x for x in d.rglob("*") if x.is_dir()), key=lambda x: -len(x.parts)):
                if not any(sub.iterdir()):
                    sub.rmdir()
            if not any(d.iterdir()):
                d.rmdir()
    print(f"wrote {len(stale)}, removed {len(extra)}, {len(files)} generated files")
    return 0


def self_check() -> int:
    assert bash_prefix("Bash(git push:*)") == ["git", "push"]
    assert bash_prefix("Bash(rm -rf:*)") == ["rm", "-rf"]
    assert bash_prefix("Bash(python)") == ["python"]
    assert bash_prefix("Read(./.env)") is None
    assert bash_prefix("Bash(git log --format=*:*)") is None
    assert relative_hook('pwsh -File "$CLAUDE_PROJECT_DIR/.claude/hooks/g.ps1"') == 'pwsh -File ".claude/hooks/g.ps1"'
    fm, body = split_frontmatter('---\nname: x\ndescription: "a \\"b\\""\n---\nBody $ARGUMENTS\n')
    assert fm == {"name": "x", "description": 'a "b"'} and body == "Body $ARGUMENTS\n", (fm, body)
    assert toml_multiline("it's\n") == "'''\nit's\n'''"
    assert toml_multiline("ends'") == '"ends\'"'

    with tempfile.TemporaryDirectory() as d:
        root = Path(d)
        (root / ".claude/skills/demo").mkdir(parents=True)
        (root / ".claude/skills/demo/SKILL.md").write_text("---\nname: demo\ndescription: d\n---\nx\n", encoding="utf-8")
        (root / ".claude/commands").mkdir()
        (root / ".claude/commands/go.md").write_text('---\ndescription: "Go"\n---\nDo $ARGUMENTS\n', encoding="utf-8")
        (root / ".claude/agents").mkdir()
        (root / ".claude/agents/rev.md").write_text('---\nname: rev\ndescription: "Reviews. Specifically: <example>"\ntools: Read, Grep\n---\nReview it.\n', encoding="utf-8")
        (root / ".claude/rules").mkdir()
        (root / ".claude/rules/r.md").write_text("# Rule: be careful\n\nText.\n", encoding="utf-8")
        (root / ".claude/settings.json").write_text(json.dumps({
            "permissions": {"allow": ["Bash(python:*)"], "ask": ["Bash(git push:*)", "Write(data/raw/**)"],
                            "deny": ["Read(./.env)", "Bash(rm -rf:*)"]},
            "hooks": {"PreToolUse": [{"matcher": "Bash", "hooks": [{"type": "command", "command": 'pwsh -File "$CLAUDE_PROJECT_DIR/.claude/hooks/g.ps1"'}]}],
                      "UserPromptSubmit": [{"hooks": [{"type": "command", "command": "x"}]}]}}), encoding="utf-8")
        (root / ".mcp.json").write_text(json.dumps({"mcpServers": {"m": {"command": "uvx", "args": ["s==1"]}, "h": {"type": "http", "url": "https://e/mcp"}}}), encoding="utf-8")
        (root / ".agents").mkdir()
        (root / ".agents/keep.md").write_text("not ours", encoding="utf-8")
        (root / ".gemini/commands").mkdir(parents=True)  # what an older version generated
        (root / ".gemini/commands/go.toml").write_text("stale", encoding="utf-8")
        (root / ".gemini/settings.json").write_text("{}", encoding="utf-8")
        (root / ".geminiignore").write_text(".env\n", encoding="utf-8")
        (root / ".codex/agents").mkdir(parents=True)
        (root / ".codex/agents/old.toml").write_text("stale", encoding="utf-8")

        files, gaps = build(root)
        assert not any(p.startswith(".gemini") for p in files), sorted(files)
        assert list(gaps) == ["Codex", "Antigravity"], list(gaps)

        assert run(root, check=True) == 1
        assert run(root, check=False) == 0
        assert run(root, check=True) == 0
        assert not list(root.glob(".gemini*")), list(root.glob(".gemini*"))  # retired output removed, dir and all
        assert not (root / ".codex/agents/old.toml").exists() and (root / ".agents/keep.md").exists()
        hooks = json.loads((root / ".codex/hooks.json").read_text(encoding="utf-8"))
        assert hooks["hooks"]["PreToolUse"][0]["hooks"][0]["command"] == 'pwsh -File ".claude/hooks/g.ps1"'
        assert json.loads((root / ".agents/mcp_config.json").read_text(encoding="utf-8"))["mcpServers"]["h"] == {"serverUrl": "https://e/mcp"}
        rules = (root / ".codex/rules/workspace.rules").read_text(encoding="utf-8")
        assert 'pattern=["rm", "-rf"], decision="forbidden"' in rules and 'pattern=["git", "push"], decision="prompt"' in rules
        toml = (root / ".codex/config.toml").read_text(encoding="utf-8")
        assert '[mcp_servers.m]\ncommand = "uvx"\nargs = ["s==1"]' in toml and 'url = "https://e/mcp"' in toml
        agent = (root / ".codex/agents/rev.toml").read_text(encoding="utf-8")
        assert 'description = "Reviews."' in agent and "may only use: Read, Grep" in agent
        assert (root / ".agents/rules/r.md").read_text(encoding="utf-8").startswith("---\ntrigger: always_on\n")
        assert (root / ".agents/skills/demo/SKILL.md").exists()
        doc = (root / DOC).read_text(encoding="utf-8")
        assert "`Write(data/raw/**)` (ask) has no equivalent" in doc and "UserPromptSubmit" in doc
        assert "Gemini" not in doc and "### Codex" in doc and "### Antigravity" in doc
        (root / ".claude/commands/go.md").unlink()
        assert run(root, check=True) == 1  # a removed source leaves a stale generated file
    print("self-check ok")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--root", type=Path, default=Path("."))
    ap.add_argument("--check", action="store_true", help="exit 1 if any generated file is stale or missing")
    ap.add_argument("--self-check", action="store_true")
    args = ap.parse_args()
    if args.self_check:
        return self_check()
    return run(args.root.resolve(), args.check)


if __name__ == "__main__":
    sys.exit(main())
