#!/usr/bin/env python3
"""Generate docs/reference/CAPABILITIES.md -- the one page that answers "what can this do".

The README says how many skills there are. It does not say what any of them do,
so finding the right command means opening twelve files. This builds that index
from the frontmatter that already exists, which is also the only way it stays
true after someone adds a command.

    python scripts/gen-capabilities.py             # write docs/reference/CAPABILITIES.md
    python scripts/gen-capabilities.py --check     # exit 1 if it is stale (CI)
    python scripts/gen-capabilities.py --self-check

ponytail: regex frontmatter parse, same as validate-skills.py. These files are
hand-written and shallow; reach for PyYAML when one genuinely nests, not before.
"""
import argparse
import json
import re
import sys
from pathlib import Path

FRONTMATTER_RE = re.compile(r"\A---\r?\n(.*?)\r?\n---\r?\n", re.DOTALL)
# an agent description carries usage examples after this marker; a table wants the claim only
EXAMPLES_RE = re.compile(r"\s*(?:Specifically:|<example>)", re.DOTALL)
# every description states its claim, then why it exists; the table wants the claim
RATIONALE_RE = re.compile(r"\s+(?:because|It exists)\b")
OUT = Path("docs/reference/CAPABILITIES.md")
BANNER = "<!-- Generated by scripts/gen-capabilities.py from .claude/ and skills/. Do not edit by hand. -->"


def frontmatter(text: str) -> dict[str, str]:
    """Top-level key/value pairs, with indented continuation lines folded in."""
    m = FRONTMATTER_RE.match(text)
    if not m:
        return {}
    out: dict[str, str] = {}
    key = None
    for line in m.group(1).splitlines():
        if not line.strip():
            continue
        if line[:1] in " \t" and key:
            out[key] += " " + line.strip()
            continue
        if ":" not in line:
            continue
        key, _, value = line.partition(":")
        key = key.strip()
        out[key] = unquote(value.strip())
    return out


def unquote(value: str) -> str:
    """Strip YAML quoting and expand the escapes a quoted scalar can carry."""
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        value = value[1:-1]
        value = value.replace('\\"', '"').replace("\\n", "\n")
    return value.strip()


def cell(text: str) -> str:
    """Make a string safe inside a markdown table cell."""
    return " ".join(text.split()).replace("|", "\\|")


def gist(desc: str) -> str:
    """The claim, minus the rationale and any usage examples."""
    desc = EXAMPLES_RE.split(desc, maxsplit=1)[0]
    desc = RATIONALE_RE.split(desc, maxsplit=1)[0]
    return cell(desc).rstrip(" -—,;:")


def read(path: Path) -> dict[str, str]:
    return frontmatter(path.read_text(encoding="utf-8", errors="replace"))


def collect(root: Path) -> dict[str, list[tuple[Path, dict[str, str]]]]:
    claude = root / ".claude"
    return {
        "commands": [(p, read(p)) for p in sorted((claude / "commands").glob("*.md"))],
        "skills": [(p, read(p)) for p in sorted((claude / "skills").glob("*/SKILL.md"))],
        "agents": [(p, read(p)) for p in sorted((claude / "agents").glob("*.md"))],
        "portable": [(p, read(p)) for p in sorted((root / "skills").glob("*/SKILL.md"))],
    }


def agents_title(root: Path) -> str:
    """The workspace name from AGENTS.md's first heading ("# AGENTS.md: Science Agent")."""
    path = root / "AGENTS.md"
    if not path.exists():
        return ""
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("# "):
            return re.sub(r"^AGENTS\.md\s*[:—–-]\s*", "", line[2:].strip())
    return ""


def render(root: Path) -> str:
    plugin_path = root / ".claude-plugin" / "plugin.json"
    plugin = json.loads(plugin_path.read_text(encoding="utf-8")) if plugin_path.exists() else {}
    # Not the folder name alone: CI checks out under the repo name, so a title taken from
    # the local folder makes --check fail on every push.
    title = plugin.get("displayName") or agents_title(root) or root.name
    items = collect(root)
    n_cmd, n_skill, n_agent = (len(items[k]) for k in ("commands", "skills", "agents"))

    L: list[str] = []
    L.append(f"# {title} — what it can do")
    L.append("")
    L.append(BANNER)
    L.append("")
    if plugin.get("description"):
        L.append(plugin["description"])
        L.append("")
    L.append(
        f"**{n_cmd} commands · {n_skill} skills · {n_agent} agents.** "
        "[Commands](#commands) · [Skills](#skills) · [Agents](#agents) · "
        "[Portable skills](#portable-skills) · "
        "[How to use this](#how-to-use-this)"
    )
    L.append("")
    L.append("---")
    L.append("")

    L.append("## Commands")
    L.append("")
    L.append(
        "You type these. Open a Claude Code session in this repo, type the command, "
        "and pass the argument shown. Each one carries its own sequence and its own "
        "refusals -- click through to read what it actually does."
    )
    L.append("")
    L.append("| Command | Argument | What it does |")
    L.append("|:---|:---|:---|")
    for path, fm in items["commands"]:
        arg = fm.get("argument-hint", "")
        arg = f"`{cell(arg)}`" if arg else "—"
        rel = f"../../.claude/commands/{path.name}"
        L.append(f"| [`/{path.stem}`]({rel}) | {arg} | {cell(fm.get('description', ''))} |")
    L.append("")

    L.append("## Skills")
    L.append("")
    L.append(
        "You do not invoke these. Claude loads one when the work matches it, and the "
        "**Say this** column is the vocabulary that makes that happen. Open a skill "
        "to read the method it applies."
    )
    L.append("")
    L.append("| Skill | Use it for | Say this |")
    L.append("|:---|:---|:---|")
    for path, fm in items["skills"]:
        use, _, trig = fm.get("description", "").partition("Triggered by")
        rel = f"../../.claude/skills/{path.parent.name}/SKILL.md"
        L.append(
            f"| [`{path.parent.name}`]({rel}) | {gist(use)} "
            f"| {cell(trig).strip(' .') or '—'} |"
        )
    L.append("")

    L.append("## Agents")
    L.append("")
    L.append(
        "Claude dispatches these at the matching step, or you ask for one by name -- "
        '*"use the <name> on this"*. The **read-only** ones are critics: they report '
        "findings and cannot touch your files."
    )
    L.append("")
    L.append("| Agent | What it does | Access | Tools |")
    L.append("|:---|:---|:---|:---|")
    for path, fm in items["agents"]:
        rel = f"../../.claude/agents/{path.name}"
        tools = fm.get("tools", "")
        writes = {"Write", "Edit"} & {t.strip() for t in tools.split(",")}
        access = "writes" if writes else "**read-only**"
        L.append(
            f"| [`{path.stem}`]({rel}) | {gist(fm.get('description', ''))} "
            f"| {access} | {cell(tools) or '—'} |"
        )
    L.append("")

    L.append("## Portable skills")
    L.append("")
    L.append(
        f"{len(items['portable'])} vendor-neutral skills in the root `skills/` folder. "
        "They are not wired into this workspace's sessions; they install into any agent "
        "CLI. The catalog with install notes is [`skills/README.md`](../../skills/README.md)."
    )
    L.append("")
    L.append("| Skill | Use it for |")
    L.append("|:---|:---|")
    for path, fm in items["portable"]:
        rel = f"../../skills/{path.parent.name}/SKILL.md"
        L.append(f"| [`{path.parent.name}`]({rel}) | {gist(fm.get('description', ''))} |")
    L.append("")

    L.append("## How to use this")
    L.append("")
    L.append(
        "1. **Start with a command** when one matches the job. It carries the "
        "sequence, the refusals, and where the output lands."
    )
    L.append(
        "2. **Otherwise just describe the work.** The skills trigger on their own; "
        "the *Say this* column is the wording that reaches them."
    )
    L.append(
        "3. **Ask for a critic by name** before anything leaves the repo. A refusal "
        "or a hard finding is the workspace working, not an obstacle to route around."
    )
    L.append(
        "4. **Read [`AGENTS.md`](../../AGENTS.md)** once. It is the doctrine every "
        "command and skill here assumes, and it is short."
    )
    L.append("")
    L.append("---")
    L.append("")
    L.append(
        '<p align="center">\n'
        '  <a href="../../README.md">← Repo home</a> ·\n'
        '  <a href="../README.md">\U0001F4DA Docs</a> ·\n'
        '  <a href="../../AGENTS.md">Agent doctrine</a> ·\n'
        '  <a href="../../.claude/settings.md">Why the permissions are what they are</a>\n'
        "</p>"
    )
    return "\n".join(L) + "\n"


def self_check() -> int:
    """Parse cases this has actually got wrong before."""
    assert unquote('"a \\"b\\" c"') == 'a "b" c'
    assert unquote("'plain'") == "plain"
    assert gist("Use when X — cuts — because the failure is Y.") == "Use when X — cuts"
    assert gist("Red-teams a memo. Specifically:\n\n<example>x") == "Red-teams a memo."
    # an agent description reads "<claim>. It exists because ..." -- the tail is not the claim
    assert gist("Grades evidence. It exists because authors cannot audit") == "Grades evidence."
    # the clause before "because" often ends on a comma
    assert gist("Use when editing audio, with ElevenLabs, because the failure") == "Use when editing audio, with ElevenLabs"
    assert cell("a | b\n  c") == "a \\| b c"
    # a folded frontmatter value must survive the line break
    assert frontmatter("---\nname: a\ndescription: one\n  two\n---\n")["description"] == "one two"
    # .gitattributes checks .md out as LF, but an editor can still save CRLF
    assert frontmatter("---\r\nname: a\r\n---\r\n") == {"name": "a"}
    assert frontmatter("no frontmatter") == {}
    # the title must not depend on the checkout folder's name (CI clones under the repo name)
    import tempfile
    with tempfile.TemporaryDirectory() as d:
        (Path(d) / "AGENTS.md").write_text("<!-- x -->\n# AGENTS.md: Science Agent\n", encoding="utf-8")
        assert agents_title(Path(d)) == "Science Agent"
        assert agents_title(Path(d) / "missing") == ""
    print("self-check ok")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if the file on disk is stale")
    ap.add_argument("--self-check", action="store_true", help="run the parser self-check and exit")
    args = ap.parse_args()

    if args.self_check:
        return self_check()

    root = Path(__file__).resolve().parent.parent
    out = root / OUT
    new = render(root)

    if args.check:
        old = out.read_text(encoding="utf-8") if out.exists() else ""
        if old != new:
            print(f"{OUT.as_posix()} is stale -- run: python scripts/gen-capabilities.py")
            return 1
        print(f"{OUT.as_posix()} is current")
        return 0

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(new, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
